"""Explanations shared by every page on the site.

The pages were written as companions to a lecture: if you know what the lecture
was about, their captions read fine; if you don't, they don't read at all.
Three blocks close that gap, in the order a visitor meets them:

* ``quick_start`` — open by default and short: what the page is for, two to
  four steps to try, and the one thing to notice. Someone who arrives from a
  search rather than from a slide should get the point in half a minute.
* ``how_to_read`` — the long version of the same: what is shown, what each
  group of controls changes, where to look, where the data comes from.
  Collapsed: it is read once and would otherwise push the page down for good.
* ``reference`` — definitions and formulas of the measures the page shows.
  Also collapsed.

Terms live in one ``GLOSSARY`` because the same ideas recur across pages
(accuracy on five of them, cross-validation on four), and two different
definitions of one thing confuse more than none. Formulas are markdown with
``$…$``: Streamlit renders them with KaTeX, whereas a separate ``st.latex`` per
line breaks the layout of a list. The text itself is Russian: it is UI.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["GLOSSARY", "Term", "how_to_read", "quick_start", "reference", "term"]


@dataclass(frozen=True)
class Term:
    """One idea: what it is called, what it means and how it is computed."""

    title: str
    meaning: str
    formula: str = ""
    note: str = ""

    def as_markdown(self) -> str:
        lines = [f"**{self.title}** — {self.meaning}"]
        if self.formula:
            lines.append(f"$$ {self.formula} $$")
        if self.note:
            lines.append(f"<small>{self.note}</small>")
        return "\n\n".join(lines)


