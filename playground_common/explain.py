QUICK_START_TITLE = "Как пользоваться"
DETAILS_TITLE = "Подробнее о странице"


def quick_start(
    st,
    *,
    purpose: str,
    steps: tuple[str, ...],
    notice: str,
    title: str = QUICK_START_TITLE,
) -> None:
    """The short instruction at the top of a page: one sentence, a few steps, one point.

    Open by default, because visitors do not all come from the slide that
    already explained the page. Everything longer belongs in ``how_to_read``.
    """
    numbered = "\n".join(f"{index}. {step}" for index, step in enumerate(steps, start=1))
    with st.expander(title, expanded=True):
        st.markdown(f"{purpose}\n\n{numbered}\n\n**Главное:** {notice}")


def how_to_read(
    st,
    *,
    what: str,
    controls: str,
    watch: str,
    data: str = "",
    title: str = DETAILS_TITLE,
    expanded: bool = False,
) -> None:
    """The long explanation: what is shown, what to change, where to look, where the data is from.

    Collapsed by default: ``quick_start`` above it is what a newcomer reads
    first, and this is for whoever wants the rest.
    """
    with st.expander(title, expanded=expanded):
        st.markdown(
            f"**Что здесь показано.** {what}\n\n"
            f"**Что можно менять.** {controls}\n\n"
            f"**Куда смотреть.** {watch}"
            + (f"\n\n**Откуда данные.** {data}" if data else "")
        )


def reference(
    st,
    *keys: str,
    extra: tuple[Term, ...] = (),
    title: str = "Метрики и формулы",
) -> None:
    """A collapsed reference for the page's measures: a definition and a formula for each."""
    terms = [GLOSSARY[key] for key in keys] + list(extra)
    with st.expander(title, expanded=False):
        # Notes are wrapped in <small>; without this flag Streamlit prints the tag as text.
        st.markdown(
            "\n\n---\n\n".join(item.as_markdown() for item in terms),
            unsafe_allow_html=True,
        )
